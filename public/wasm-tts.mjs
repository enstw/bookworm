// sherpa's zh text-normalization tables, in the order they are applied — the
// order is load-bearing, matches sherpa's own config, and arrives as the
// manifest's key order. The real kaldifst (built to a 338 KB wasm upstream
// in wasmtts) applies them; the JS applier is now the node tests' oracle only.
const RULE_LABELS = ["號碼規則", "日期規則", "數字規則"];
const RULE_FILES = PACK.rules.map((f, i) => ({ ...f, label: RULE_LABELS[i] ?? "規則表" }));

export const PACK_FILES = [...MODEL_FILES, ...RULE_FILES];

// The ort build this engine was verified against, byte-for-byte. The release
// filename carries the version, so a pin bump that outruns the assets release
// 404s instead of drifting (CI's sync step re-cuts it before deploy); this
// catches the other direction — a re-cut release under the same name — and
// says so, rather than failing inside instantiation.
const ORT_WASM_BYTES = ORT_WASM.bytes;

// Gates on MODEL_FILES, not PACK_FILES: the rule tables are part of the pack
// /wasmtest downloads, but they are not what makes the engine able to speak.
// Gating on them would have taken a phone holding a complete pre-table pack off
// the offline engine until it visited /wasmtest again — and it does not need to,
// because ensureEngine fetches them softly and caches them, so a device that is
// online picks them up on its next init by itself.
export async function packReady() {
  try {
    const cache = await caches.open(CACHE);
    for (const f of MODEL_FILES)
      if (!(await cache.match("/api/wasmtts/" + f.name))) return false;
    return true;
  } catch { return false; } // private mode: no cache, no pack
}

// Not ready, but not empty either: a device that HAD the offline voice and
// lost it to a pack change (a model bump renames a file, so packReady goes
// false on a phone that did nothing wrong) or a half-finished download. The
// caller can tell that reader why the offline voice went missing — a fresh
// device stays quiet, because it never had anything to lose.
export async function packStale() {
  try {
    const cache = await caches.open(CACHE);
    return (await cache.keys()).length > 0 && !(await packReady());
  } catch { return false; }
}

// /wasmtest's 清除快取 button; here because the module owns the cache name.
export async function clearPack() {
  try { return await caches.delete(CACHE); } catch { return false; }
}

// What tapping the pill's 重新下載 would actually pull over the network — a
// stale pack usually keeps most of its files (a model bump renames one), so
// this is how the button can be honest about the bytes before it is tapped.
export async function packMissingBytes() {
  try {
    const cache = await caches.open(CACHE);
    let missing = 0;
    for (const f of PACK_FILES)
      if (!(await cache.match("/api/wasmtts/" + f.name))) missing += f.bytes;
    return missing;
  } catch { return PACK_FILES.reduce((s, f) => s + f.bytes, 0); }
}

// The whole pack, one file at a time, into the shared cache — /wasmtest and
// the reader's stale-pack pill both call this, so either path primes the
// other. onFile fires after every file (cached ones too) with cumulative
// bytes, which is all a progress line or a percentage needs. Every caller
// sits behind an explicit tap that names the size: ▶ itself must never
// quietly pull ~145 MB over cellular.
export async function downloadPack(onFile) {
  let cache = null;
  try { cache = await caches.open(CACHE); } catch { /* private mode: no cache */ }
  const totalBytes = PACK_FILES.reduce((s, f) => s + f.bytes, 0);
  let gotBytes = 0;
  for (const f of PACK_FILES) {
    const url = "/api/wasmtts/" + f.name;
    const cached = !!(await cache?.match(url));
    let secs = 0;
    if (!cached) {
      const t = performance.now();
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${f.name} HTTP ${res.status}`);
      if (cache) await cache.put(url, res.clone());
      await res.arrayBuffer(); // time the full body, not just the headers
      secs = (performance.now() - t) / 1000;
    }
    gotBytes += f.bytes;
    onFile?.({ ...f, cached, secs, gotBytes, totalBytes });
  }
}

// Cache-first is correct ONLY for the release binaries: their filename
// carries the version, so their bytes can never change under a URL. The
// same-origin JS modules and vendor bundles are the opposite — they change
// bytes at fixed URLs with every edit or pin bump, and the copy parked here
// outlives every SHELL bump (this is bw-wasmtts, not the shell cache), so a
// cache-first read runs LAST YEAR'S engine forever. fresh=true serves the
// network's copy — the service worker already bounds that at 1 s and answers
// from its shell cache offline — and keeps the parked copy only as the
// no-service-worker last resort. Found the hard way: the phone inited the
// 1.26-dev ort UMD against the 1.27.0 wasm because its parked copy shadowed
// the deploy.
async function cachedBuf(url, fresh = false) {
  let cache = null;
  try { cache = await caches.open(CACHE); } catch { /* private mode */ }
  if (fresh) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url} HTTP ${res.status}`);
      if (cache) await cache.put(url, res.clone());
      return res.arrayBuffer();
    } catch (err) {
      const parked = await cache?.match(url);
      if (parked) return parked.arrayBuffer();
      throw err;
    }
  }
  let res = await cache?.match(url);
  if (!res) {
    res = await fetch(url);
    if (!res.ok) throw new Error(`${url} HTTP ${res.status}`);
    if (cache) await cache.put(url, res.clone());
  }
  return res.arrayBuffer();
}

// ---- inference worker -----------------------------------------------------
// session.run blocks JS for hundreds of ms per sentence — in a Worker that
// never touches the main thread's playback handlers. Everything the worker
// needs arrives as a buffer and is importScripts'd from a blob URL, so it
// works offline and never re-downloads. The one exception is ort's loader
// glue: ort import()s it by URL, which a blob cannot satisfy in a classic
// worker, so it stays a same-origin asset and rides the service worker shell.
const WORKER_SRC = `
let rt, frontend, engine; // rt, not ort: the UMD script declares the global "ort" itself
onmessage = async (e) => {
  const m = e.data;
  try {
    if (m.type === "init") {
      const js = (buf) => URL.createObjectURL(new Blob([buf], { type: "text/javascript" }));
      importScripts(js(m.ortJs), js(m.lameJs), js(m.kaldifstGlueJs), js(m.kaldifstJs), js(m.frontendJs), js(m.taiwanJs), js(m.synthesisJs));
      rt = self.ort;
      rt.env.wasm.numThreads = 1;
      rt.env.wasm.proxy = false;
      rt.env.wasm.wasmBinary = m.ortWasm;
      rt.env.wasm.wasmPaths = { mjs: m.glueUrl };
      // The rule tables read every ordinary number, date and phone number in the
      // book; the JS rules in matcha-frontend.js stay behind them as the reading
      // for a device that has the voice pack but not the tables. The applier is
      // the real kaldifst wasm (its own linear memory, 16 MiB — nothing shared
      // with ort); its bytes arrive as a buffer and become a blob URL because a
      // blob worker has no same-origin base to resolve a path against. A
      // normalizer that fails to instantiate is the same case as missing
      // tables — say so and speak.
      let ruleNormalizer, rules = 0, rulesErr = "";
      if (m.ruleFsts) {
        try {
          ruleNormalizer = await self.MatchaKaldifst.createNormalizer({
            moduleFactory: self.KaldifstNormalizerModule,
            wasmUrl: URL.createObjectURL(new Blob([m.kaldifstWasm], { type: "application/wasm" })),
            fstBuffers: m.ruleFsts,
          });
          rules = m.ruleFsts.length;
        } catch (err) {
          rulesErr = String(err.message ?? err); // reported with ready, not as an init failure
        }
      }
      // The taiwan profile compiles upstream's reviewed reading decisions
      // (phrase overrides plus contextual rules for 得/著/長/還…) out of the
      // review ledger; the local OVERRIDES stack on top, because a reading
      // verified by ear on this app outranks the ledger until it graduates.
      const profile = self.MatchaTaiwanProfile.createConfig(JSON.parse(new TextDecoder().decode(m.review)));
      frontend = self.MatchaFrontend.createFrontend({
        lexiconText: new TextDecoder().decode(m.lexicon),
        tokensText: new TextDecoder().decode(m.tokens),
        pronunciationOverrides: { ...profile.pronunciationOverrides, ...m.overrides },
        contextualRules: profile.contextualRules,
        ruleNormalizer,
      });
      // The playback recipe (noise/length/silence) is the voice pack's own:
      // matcha-assets.json's synthesis block, ear-verified on device and
      // graduated upstream 2026-08-15 — rationale in wasmtts platform/README.
      // Hardcoding a knob here is the fork the pack manifest exists to
      // prevent; vendor.mjs fails the build if the pin ships without it.
      engine = self.MatchaSynthesis.createEngine({ ORT: rt, ...m.synth });
      const info = await engine.init({
        acousticModel: new Uint8Array(m.acoustic),
        vocoderModel: new Uint8Array(m.vocoder),
      });
      postMessage({ type: "ready", initMs: info.wallMs, lexiconSize: frontend.lexiconSize, rules, rulesErr,
        profileWords: Object.keys(profile.pronunciationOverrides).length, profileRules: profile.contextualRules.length });
    } else if (m.type === "speak") {
      const t = performance.now();
      // one unknown glyph must never stop a book: drop it and count it
      const f = frontend.tokensFor(m.text, { allowUnknown: true });
      if (!f.ids.length) return postMessage({ type: "spoke", k: m.k, empty: true });
      const s = await engine.synthesize(f.ids, {});
      const w = s.waveform;
      // a numerical blow-up is silence or NaN, and both play as a dead unit the
      // reader cannot distinguish from a pause — refuse it here instead
      if (w.finiteSamples !== s.samples.length || w.peak === 0 || w.rms === 0)
        throw new Error("waveform not audible (peak " + w.peak + ", rms " + w.rms + ")");
      const ms = performance.now() - t;
      if (!m.mp3) {
        const pcm = s.samples;
        return postMessage({ type: "spoke", k: m.k, pcm, secs: s.audioSeconds, ms, unknown: f.unknown.length }, [pcm.buffer]);
      }
      // one self-contained mp3 stream per unit; frames concatenate cleanly
      // in a sequence-mode SourceBuffer
      const n = s.samples.length, i16 = new Int16Array(n);
      for (let i = 0; i < n; i++) i16[i] = Math.max(-1, Math.min(1, s.samples[i])) * 32767 | 0;
      const enc = new self.lamejs.Mp3Encoder(1, s.sampleRate, 96);
      const parts = [];
      for (let o = 0; o < n; o += 1152) parts.push(enc.encodeBuffer(i16.subarray(o, Math.min(n, o + 1152))));
      parts.push(enc.flush());
      let len = 0;
      for (const p of parts) len += p.length;
      const buf = new Uint8Array(len);
      let o = 0;
      for (const p of parts) { buf.set(p, o); o += p.length; }
      postMessage({ type: "spoke", k: m.k, buf: buf.buffer, secs: s.audioSeconds, ms, unknown: f.unknown.length }, [buf.buffer]);
    }
  } catch (err) {
    postMessage({ type: "err", k: m.k, msg: String(err?.message ?? err) });
  }
};`;

// what init actually decided — the player's flight recorder reads this
export const engineInfo = { threads: 0, rules: 0, profileWords: 0, profileRules: 0 };

let engine = null; // singleton promise — models stay loaded across sessions

// → { speakChunk } — throws when init fails (player falls back to stream)
export function ensureEngine() {
  return engine ??= (async () => {
    navigator.storage?.persist?.().catch(() => {});
    const [acoustic, vocoder, lexicon, tokens, ortWasm, ortJs, lameJs, kaldifstGlueJs, kaldifstJs, kaldifstWasm, frontendJs, taiwanJs, review, synthesisJs, ...ruleFsts] =
      await Promise.all([
        ...MODEL_FILES.map((f) => cachedBuf("/api/wasmtts/" + f.name)),
        cachedBuf("/vendor/wasmtts/ort-wasm.min.js", true),
        cachedBuf("/vendor/wasmtts/lame.min.js", true),
        cachedBuf("/vendor/wasmtts/matcha-kaldifst-normalizer.js", true),
        cachedBuf("/vendor/wasmtts/kaldifst-normalizer.js", true),
        cachedBuf("/vendor/wasmtts/matcha-kaldifst-normalizer.wasm", true),
        cachedBuf("/vendor/wasmtts/matcha-frontend.js", true),
        // hard requirements like the frontend itself, not soft like the rule
        // tables: both ride the deploy (and the sw shell), so a device running
        // this module version has them a fetch away — and a frontend without
        // the reviewed readings is a voice nobody signed off
        cachedBuf("/vendor/wasmtts/matcha-taiwan-profile.js", true),
        cachedBuf("/vendor/wasmtts/matcha-g2p-review.json", true),
        cachedBuf("/vendor/wasmtts/matcha-synthesis.js", true),
        // Soft, unlike everything above it: a device holding a pack cut before
        // the tables existed has all 138 MB of what it needs to speak, and must
        // not lose offline audio over 212 KB it has never heard of. Absent
        // tables leave prepareText on the JS number rules — what shipped before.
        ...RULE_FILES.map((f) => cachedBuf("/api/wasmtts/" + f.name).catch(() => null)),
      ]);
    if (ortWasm.byteLength !== ORT_WASM_BYTES)
      throw new Error(`ort wasm is ${ortWasm.byteLength} B, expected ${ORT_WASM_BYTES} — the release and package.json disagree; re-cut the release or re-verify on device`);

    const worker = new Worker(URL.createObjectURL(new Blob([WORKER_SRC], { type: "text/javascript" })));
    const pending = new Map();
    worker.onmessage = (e) => {
      const m = e.data;
      if (m.type === "err") console.warn("wasm-tts worker:", m.msg);
      const r = pending.get(m.k);
      pending.delete(m.k);
      r?.(m.type === "err" ? null : m);
    };
    let seq = 0;
    const call = (msg, transfer) => new Promise((r) => {
      pending.set(++seq, r);
      worker.postMessage({ ...msg, k: seq }, transfer);
    });
    // all three or none: a half-applied chain is a reading nobody has verified
    const rules = ruleFsts.every(Boolean) ? ruleFsts : null;
    const up = await new Promise((r) => {
      pending.set(undefined, r);
      worker.postMessage(
        { type: "init", ortJs, lameJs, kaldifstGlueJs, kaldifstJs, kaldifstWasm, frontendJs, taiwanJs, review, synthesisJs, ortWasm, acoustic, vocoder, lexicon, tokens,
          ruleFsts: rules, overrides: OVERRIDES, synth: PACK.synthesis,
          glueUrl: new URL("/vendor/wasmtts/ort-wasm-simd-threaded.mjs", location.origin).href },
        [ortJs, lameJs, kaldifstGlueJs, kaldifstJs, kaldifstWasm, frontendJs, taiwanJs, review, synthesisJs, ortWasm, acoustic, vocoder, lexicon, tokens, ...(rules ?? [])],
      );
    });
    if (up === null) { worker.terminate(); throw new Error("wasm-tts init failed"); }
    engineInfo.threads = 1;
    engineInfo.rules = up.rules ?? 0;
    engineInfo.profileWords = up.profileWords ?? 0;
    engineInfo.profileRules = up.profileRules ?? 0;
    if (up.rulesErr) console.warn("wasm-tts: kaldifst normalizer unusable, JS number rules only —", up.rulesErr);
    console.log(`wasm-tts ready: matcha zh-en ${RATE}Hz, 1 thread, ${up.lexiconSize} lexicon entries, ${up.rules ? `${up.rules} rule tables (kaldifst wasm)` : "JS number rules"}, taiwan profile ${up.profileWords}w+${up.profileRules}r, init ${Math.round(up.initMs)}ms`);

    // Everything this engine does not use is dead weight in a cache iOS evicts
    // under pressure — and the piper/melo/fanchen era left several hundred MB
    // of it. Sweep by keep-set rather than by name so this never needs editing
    // again; /wasmtest re-downloads on demand if a diagnostic wants something.
    caches.open(CACHE).then(async (c) => {
      const keep = new Set([
        ...PACK_FILES.map((f) => "/api/wasmtts/" + f.name),
        // the small same-origin files cachedBuf also parks here — they were
        // being swept and re-fetched on every single init
        "/vendor/wasmtts/ort-wasm.min.js", "/vendor/wasmtts/lame.min.js",
        "/vendor/wasmtts/matcha-kaldifst-normalizer.js", "/vendor/wasmtts/kaldifst-normalizer.js",
        "/vendor/wasmtts/matcha-kaldifst-normalizer.wasm",
        "/vendor/wasmtts/matcha-frontend.js", "/vendor/wasmtts/matcha-synthesis.js",
        "/vendor/wasmtts/matcha-taiwan-profile.js", "/vendor/wasmtts/matcha-g2p-review.json",
      ]);
      for (const req of await c.keys()) {
        const p = new URL(req.url).pathname;
        if (!keep.has(p) && await c.delete(req)) console.log("wasm-tts: evicted stale " + p);
      }
    }).catch(() => {});

    // Synthesize one chunk's prompt text as a stream of sentence-sized units.
    // onUnit({blob|buf, secs, frac0, frac1}) — fracs are the unit's span over
    // the prompt (proportional char mapping, like the other engines); await
    // its return value for backpressure, return false to abort. mp3=true
    // yields mp3 frames (unit.buf) for the MediaSource path instead of a WAV
    // blob — iOS only keeps lock-screen audio on one continuous timeline, and
    // MSE does not eat WAV.
    async function speakChunk(prompt, onUnit, mp3 = false) {
      const segs = segments(prompt);
      const total = prompt.length || 1;
      let held = null; // start of a segment that produced nothing, folded forward
      for (const s of segs) {
        const r = await call({ type: "speak", text: s.text, mp3 });
        // one unreadable sentence must not kill the readout; its span joins
        // the next unit so the char mapping stays continuous
        if (!r || r.empty) { held ??= s.start; continue; }
        const unit = {
          secs: r.secs,
          ms: r.ms, // compute time — the flight recorder's ×N
          frac0: (held ?? s.start) / total,
          frac1: s.end / total,
        };
        held = null;
        if (mp3) unit.buf = r.buf;
        else unit.blob = mkWav(r.pcm, RATE);
        if ((await onUnit(unit)) === false) return false;
      }
      return true;
    }
    return { speakChunk };
  })().catch((e) => { engine = null; throw e; });
}
